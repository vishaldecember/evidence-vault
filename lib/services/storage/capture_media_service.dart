import 'dart:io';

import 'package:file_picker/file_picker.dart';
import 'package:flutter/foundation.dart';
import 'package:path/path.dart' as p;

import '../../models/workspace_capture_mode.dart';
import '../../diagnostics/file_p0_trace.dart';
import '../audio_capture_service.dart';
import '../document_import_service.dart';
import '../photo_capture_service.dart';
import '../video_capture_service.dart';

/// Local media acquired for a workspace capture before Firebase upload.
class CapturedMediaFile {
  const CapturedMediaFile({
    required this.localPath,
    required this.fileName,
    required this.fileSizeBytes,
    this.thumbnailPath,
  });

  final String localPath;
  final String fileName;
  final int fileSizeBytes;
  final String? thumbnailPath;
}

/// Acquires real device media for Photo / Video / Voice / Attachment captures.
///
/// Notes are text-only and return null. Does not upload — Storage does.
abstract final class CaptureMediaService {
  /// Returns null when the user cancels or [mode] has no binary payload.
  static Future<CapturedMediaFile?> acquire(WorkspaceCaptureMode mode) async {
    if (kIsWeb) {
      return null;
    }

    final path = await switch (mode) {
      WorkspaceCaptureMode.photo => PhotoCaptureService.capturePhoto(),
      WorkspaceCaptureMode.video => VideoCaptureService.captureVideo(),
      WorkspaceCaptureMode.voice => _captureVoice(),
      WorkspaceCaptureMode.file => DocumentImportService.importDocument(),
      WorkspaceCaptureMode.note => null,
    };

    if (mode == WorkspaceCaptureMode.file) {
      FileP0Trace.step(
        'ACQUIRE_PATH',
        result: path == null || path.isEmpty ? 'NULL' : 'OK',
        path: path,
      );
    }

    if (path == null || path.isEmpty) {
      if (mode == WorkspaceCaptureMode.file) {
        FileP0Trace.step('ACQUIRE_RESULT', result: 'NULL');
      }
      return null;
    }

    final file = File(path);
    if (!await file.exists()) {
      if (mode == WorkspaceCaptureMode.file) {
        FileP0Trace.failure('ACQUIRE_FILE_MISSING', path: path);
      }
      return null;
    }

    final media = CapturedMediaFile(
      localPath: path,
      fileName: p.basename(path),
      fileSizeBytes: await file.length(),
      // Photo uses the capture file as an instant placeholder; video/file
      // thumbs are generated by ThumbnailJob so acquire never blocks.
      thumbnailPath: switch (mode) {
        WorkspaceCaptureMode.photo => path,
        WorkspaceCaptureMode.file => _imagePathOrNull(path),
        WorkspaceCaptureMode.video ||
        WorkspaceCaptureMode.voice ||
        WorkspaceCaptureMode.note =>
          null,
      },
    );
    if (mode == WorkspaceCaptureMode.file) {
      FileP0Trace.step(
        'ACQUIRE_RESULT',
        result: 'VALID',
        fileName: media.fileName,
        fileSize: media.fileSizeBytes,
        path: media.localPath,
      );
    }
    return media;
  }

  static String? _imagePathOrNull(String path) {
    final lower = path.toLowerCase();
    if (lower.endsWith('.jpg') ||
        lower.endsWith('.jpeg') ||
        lower.endsWith('.png') ||
        lower.endsWith('.webp') ||
        lower.endsWith('.gif')) {
      return path;
    }
    return null;
  }

  /// Records a short voice clip: start → wait for [stopSignal] → stop.
  ///
  /// When [stopSignal] is null, falls back to picking an audio file so
  /// headless/tests can still supply media without a recording UI redesign.
  static Future<String?> _captureVoice({
    Future<void>? stopSignal,
  }) async {
    if (stopSignal != null) {
      await AudioCaptureService.start();
      await stopSignal;
      return AudioCaptureService.stop();
    }

    final result = await FilePicker.platform.pickFiles(
      type: FileType.custom,
      allowedExtensions: const ['m4a', 'aac', 'mp3', 'wav', 'caf'],
      allowMultiple: false,
      withData: false,
    );
    if (result == null || result.files.isEmpty) {
      return null;
    }
    return result.files.single.path;
  }

  /// Records until [stopSignal] completes — used by workspace voice capture UI.
  static Future<CapturedMediaFile?> recordVoiceUntil(
    Future<void> stopSignal,
  ) async {
    if (kIsWeb) {
      return null;
    }
    await AudioCaptureService.start();
    await stopSignal;
    final path = await AudioCaptureService.stop();
    if (path == null) {
      return null;
    }
    final file = File(path);
    if (!await file.exists()) {
      return null;
    }
    return CapturedMediaFile(
      localPath: path,
      fileName: p.basename(path),
      fileSizeBytes: await file.length(),
    );
  }
}
