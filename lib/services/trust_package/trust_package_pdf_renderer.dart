import 'dart:typed_data';

import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../domain/trust_package/trust_package.dart';
import '../trust_package_scorecard_service.dart';
import 'trust_package_export_metadata.dart';

/// Renders a professional PDF from [TrustPackage] only.
abstract final class TrustPackagePdfRenderer {
  static String pdfText(String value) {
    return value
        .replaceAll('•', '-')
        .replaceAll('✓', '')
        .replaceAll(RegExp(r'[\u{1F300}-\u{1FAFF}]', unicode: true), '')
        .trim();
  }

  static Future<Uint8List> buildPdf(TrustPackage package) async {
    final embedded = TrustPackageExportMetadata.embedded(package);
    final document = pw.Document(
      title: package.incidentSummary.incidentName,
      author: package.metadata.generatedBy,
      creator: 'Evidence Vault Trust Package Export',
      subject: embedded['trustPackageId'],
      keywords:
          'trustPackageId=${embedded['trustPackageId']};'
          'packageVersion=${embedded['packageVersion']};'
          'generatedTimestamp=${embedded['generatedTimestamp']};'
          'incidentVersion=${embedded['incidentVersion']};'
          'generatedBy=${embedded['generatedBy']}',
    );

    final quality = TrustPackageScorecardService.evaluate(package);
    final groupsById = {
      for (final group in package.relationshipGroupsSection.groups)
        group.groupId: group,
    };
    final dateFormat = DateFormat('d MMMM yyyy \'at\' HH:mm');
    final timestampFormat = DateFormat('d MMM yyyy \'at\' HH:mm');

    var pageNumber = 0;

    pw.Widget footer() {
      pageNumber++;
      return pw.Container(
        alignment: pw.Alignment.centerRight,
        margin: const pw.EdgeInsets.only(top: 12),
        child: pw.Text(
          'Page $pageNumber',
          style: pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
        ),
      );
    }

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Trust Package'),
          pw.SizedBox(height: 8),
          pw.Text(
            package.incidentSummary.incidentName,
            style: pw.TextStyle(
              fontSize: 24,
              fontWeight: pw.FontWeight.bold,
              color: PdfColors.blue900,
            ),
          ),
          pw.SizedBox(height: 20),
          _factRow('Incident Type', package.incidentSummary.incidentType),
          _factRow('Incident Status', package.incidentSummary.incidentStatus),
          _factRow(
            'Generated Date',
            dateFormat.format(package.metadata.generatedAt),
          ),
          _factRow('Generated By', package.metadata.generatedBy),
          _factRow(
            'Trust Package Version',
            package.metadata.packageVersion,
          ),
          _factRow(
            'Investigation Confidence',
            package.incidentSummary.investigationConfidence,
          ),
          _factRow(
            'Reconstruction Health',
            package.incidentSummary.reconstructionHealth,
          ),
          pw.SizedBox(height: 16),
          _metadataBlock(embedded),
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Executive Summary'),
          pw.SizedBox(height: 12),
          ..._executiveSummaryBlocks(package),
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Chronological Timeline'),
          pw.SizedBox(height: 12),
          if (package.timelineSection.entries.isEmpty)
            _emptyMessage('No timeline anchors are included in this package.')
          else
            ...[
              for (final entry in package.timelineSection.entries)
                _timelineBlock(entry, groupsById, timestampFormat),
            ],
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Relationship Groups'),
          pw.SizedBox(height: 12),
          if (package.relationshipGroupsSection.groups.isEmpty)
            _emptyMessage('No relationship groups are included in this package.')
          else
            ...[
              for (final group in package.relationshipGroupsSection.groups)
                _relationshipGroupBlock(group),
            ],
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Reconstruction Narrative'),
          pw.SizedBox(height: 12),
          if (package.reconstructionSection.events.isEmpty)
            _emptyMessage('No narrative events are included in this package.')
          else
            ...[
              for (final event in package.reconstructionSection.events)
                _narrativeBlock(event),
            ],
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Evidence Appendix'),
          pw.SizedBox(height: 12),
          if (package.evidenceAppendix.entries.isEmpty)
            _emptyMessage('No evidence items are included in this package.')
          else
            ...[
              for (final entry in package.evidenceAppendix.entries)
                _appendixBlock(entry, groupsById, timestampFormat),
            ],
        ],
        footer: (context) => footer(),
      ),
    );

    final narrativeCompleteness = quality.indicators
        .firstWhere(
          (entry) =>
              entry.label == TrustPackageScorecardService.narrativeReferencesLabel,
        )
        .statusLabel;
    final evidenceIntegrity = package.integritySummary.missingReferences.isEmpty
        ? 'Verified'
        : 'Review Required';
    final referenceCompleteness =
        package.integritySummary.missingReferences.isEmpty
            ? 'Verified'
            : 'Unverified';

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading(TrustPackIntegrityLabels.sectionTitle),
          pw.SizedBox(height: 12),
          _factRow(
            'Integrity',
            pdfText(package.integrityProvenance.packStatusLabel),
          ),
          if (package.integrityProvenance.packStatusSecondary != null)
            _factRow(
              'Verified items',
              package.integrityProvenance.packStatusSecondary!,
            ),
          _factRow(
            TrustPackIntegrityLabels.independentVerification,
            TrustPackIntegrityLabels.independentNotPerformed,
          ),
          pw.SizedBox(height: 8),
          pw.Text(
            pdfText(package.integrityProvenance.packStatusExplanation),
            style: const pw.TextStyle(fontSize: 10, lineSpacing: 1.4),
          ),
          pw.SizedBox(height: 12),
          if (package.integrityProvenance.entries.isEmpty)
            _emptyMessage(TrustPackIntegrityLabels.unavailableExplanation)
          else
            ...[
              for (final entry in package.integrityProvenance.entries)
                _integrityProvenanceBlock(entry, timestampFormat),
            ],
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) => [
          _sectionHeading('Integrity Report'),
          pw.SizedBox(height: 12),
          _factRow(
            'Timeline Integrity',
            TrustPackageScorecardService.integrityStatusLabel(
              package.integritySummary.timelineIntegrity,
            ),
          ),
          _factRow(
            'Relationship Integrity',
            TrustPackageScorecardService.integrityStatusLabel(
              package.integritySummary.relationshipIntegrity,
            ),
          ),
          _factRow('Evidence Integrity', evidenceIntegrity),
          _factRow('Narrative references verified', narrativeCompleteness),
          _factRow(
            'Validation Status',
            package.integritySummary.validationStatus,
          ),
          _factRow('References verified', referenceCompleteness),
          if (package.integritySummary.missingReferences.isNotEmpty) ...[
            pw.SizedBox(height: 12),
            pw.Text(
              'Missing References',
              style: pw.TextStyle(
                fontSize: 11,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 6),
            for (final reference in package.integritySummary.missingReferences)
              pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 4),
                child: pw.Text('- $reference', style: const pw.TextStyle(fontSize: 10)),
              ),
          ],
        ],
        footer: (context) => footer(),
      ),
    );

    document.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(48, 48, 48, 56),
        build: (context) {
          pageNumber++;
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _sectionHeading(TrustPackageExportMetadata.integrityNoticeTitle),
              pw.SizedBox(height: 16),
              pw.Text(
                TrustPackageExportMetadata.integrityNoticeBody,
                style: const pw.TextStyle(fontSize: 11, lineSpacing: 1.5),
              ),
              pw.Spacer(),
              pw.Align(
                alignment: pw.Alignment.centerRight,
                child: pw.Text(
                  'Page $pageNumber',
                  style: pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
                ),
              ),
            ],
          );
        },
      ),
    );

    return document.save();
  }

  static pw.Widget _sectionHeading(String title) {
    return pw.Text(
      title,
      style: pw.TextStyle(
        fontSize: 16,
        fontWeight: pw.FontWeight.bold,
        color: PdfColors.blue900,
      ),
    );
  }

  static pw.Widget _factRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 6),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 150,
            child: pw.Text(
              label,
              style: pw.TextStyle(
                fontSize: 10,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.grey700,
              ),
            ),
          ),
          pw.Expanded(
            child: pw.Text(value, style: const pw.TextStyle(fontSize: 10)),
          ),
        ],
      ),
    );
  }

  static pw.Widget _metadataBlock(Map<String, String> embedded) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey400),
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            'Export Metadata',
            style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 6),
          for (final entry in embedded.entries)
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 2),
              child: pw.Text(
                '${entry.key}: ${entry.value}',
                style: const pw.TextStyle(fontSize: 9),
              ),
            ),
        ],
      ),
    );
  }

  static List<pw.Widget> _executiveSummaryBlocks(TrustPackage package) {
    final stats = package.investigationSummary;
    return [
      _summaryBlock(
        'Incident Summary',
        '${package.incidentSummary.incidentName} is recorded as '
            '${package.incidentSummary.incidentStatus.toLowerCase()} '
            'with ${stats.primaryChronologyStatement}. '
            '${stats.structuralSupportStatement}.',
      ),
      _summaryBlock(
        'Timeline Summary',
        '${stats.timelineAnchorCount} timeline anchors preserve the '
            'chronological sequence of the incident.',
      ),
      _summaryBlock(
        'Relationship Summary',
        '${stats.relationshipGroupCount} relationship groups connect '
            'related evidence items.',
      ),
      _summaryBlock(
        'Narrative Summary',
        '${stats.narrativeEventCount} narrative events document the '
            'investigator reconstruction.',
      ),
      _summaryBlock(
        'Evidence Statistics',
        '${stats.recordedContextStatement}. '
            '${stats.witnessCount} witness-kind records and '
            '${stats.documentCount} note or document items are listed by type.',
      ),
    ];
  }

  static pw.Widget _summaryBlock(String heading, String body) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 12),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            heading,
            style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 4),
          pw.Text(body, style: const pw.TextStyle(fontSize: 10, lineSpacing: 1.4)),
        ],
      ),
    );
  }

  static pw.Widget _timelineBlock(
    TrustPackageTimelineEntry entry,
    Map<String, TrustPackageRelationshipGroupEntry> groupsById,
    DateFormat timestampFormat,
  ) {
    final group = entry.relationshipGroupIds.isEmpty
        ? null
        : groupsById[entry.relationshipGroupIds.first];
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 10),
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey400),
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            timestampFormat.format(entry.timestamp),
            style: pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
          ),
          pw.SizedBox(height: 4),
          pw.Text(
            entry.title,
            style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 6),
          _factRow(
            'Related Evidence',
            '${entry.relatedEvidenceIds.length}',
          ),
          _factRow(
            'Relationship Group',
            group?.groupName ?? 'No relationship group',
          ),
          _factRow(
            'Confidence',
            group?.confidenceLevel ?? 'Not assessed',
          ),
        ],
      ),
    );
  }

  static pw.Widget _relationshipGroupBlock(
    TrustPackageRelationshipGroupEntry group,
  ) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 10),
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey400),
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            group.groupName,
            style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 6),
          _factRow('Confidence', group.confidenceLevel),
          _factRow('Validation Status', pdfText(group.validationStatus)),
          _factRow(
            'Evidence References',
            '${group.memberEvidenceIds.length}',
          ),
        ],
      ),
    );
  }

  static pw.Widget _narrativeBlock(
    TrustPackageReconstructionEventEntry event,
  ) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 10),
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey400),
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            event.title,
            style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
          ),
          if (event.summary != null && event.summary!.isNotEmpty) ...[
            pw.SizedBox(height: 4),
            pw.Text(event.summary!, style: const pw.TextStyle(fontSize: 10)),
          ],
          pw.SizedBox(height: 6),
          _factRow('Confidence', event.confidence),
          _factRow('Validation Status', pdfText(event.validationStatus)),
          _factRow(
            'Supporting Evidence',
            '${event.evidenceReferenceIds.length}',
          ),
        ],
      ),
    );
  }

  static pw.Widget _appendixBlock(
    TrustPackageEvidenceAppendixEntry entry,
    Map<String, TrustPackageRelationshipGroupEntry> groupsById,
    DateFormat timestampFormat,
  ) {
    final groupNames = [
      for (final groupId in entry.relationshipGroupIds)
        groupsById[groupId]?.groupName ?? groupId,
    ];

    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 8),
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            entry.title,
            style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 4),
          _factRow('Type', entry.evidenceType),
          _factRow('Timestamp', timestampFormat.format(entry.timestamp)),
          if (entry.device != null) _factRow('Device', entry.device!),
          if (entry.location != null) _factRow('Location', entry.location!),
          if (entry.context != null) _factRow('Context', entry.context!),
          _factRow(
            'Relationship Groups',
            groupNames.isEmpty ? 'None' : groupNames.join(', '),
          ),
        ],
      ),
    );
  }

  static pw.Widget _integrityProvenanceBlock(
    TrustPackageIntegrityProvenanceEntry entry,
    DateFormat timestampFormat,
  ) {
    final clock = DateFormat('HH:mm:ss');
    final hash = entry.contentHash;
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 10),
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey400),
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            entry.title,
            style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 6),
          _factRow('Integrity', pdfText(entry.statusLabel)),
          _factRow('Original', entry.originalPreservationLabel),
          if (entry.capturedAt != null)
            _factRow(
              TrustPackIntegrityLabels.captured,
              timestampFormat.format(entry.capturedAt!),
            ),
          if (entry.preservedAt != null)
            _factRow(
              TrustPackIntegrityLabels.preserved,
              timestampFormat.format(entry.preservedAt!),
            ),
          if (entry.source != null)
            _factRow(TrustPackIntegrityLabels.source, entry.source!),
          if (entry.captureModality != null)
            _factRow(
              TrustPackIntegrityLabels.captureModality,
              entry.captureModality!,
            ),
          _factRow(
            TrustPackIntegrityLabels.location,
            pdfText(entry.locationDisplay),
          ),
          _factRow(
            TrustPackIntegrityLabels.independentVerification,
            entry.independentVerification,
          ),
          if (hash != null)
            _factRow(
              TrustPackIntegrityLabels.sha256Fingerprint,
              _hashPreview(hash),
            ),
          if (entry.history.isNotEmpty) ...[
            pw.SizedBox(height: 6),
            pw.Text(
              TrustPackIntegrityLabels.evidenceHistory,
              style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 4),
            for (final event in entry.history)
              pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 2),
                child: pw.Text(
                  '${clock.format(event.at)}   ${event.label}',
                  style: const pw.TextStyle(fontSize: 9),
                ),
              ),
          ],
        ],
      ),
    );
  }

  static String _hashPreview(String hash) {
    if (hash.length <= 16) {
      return hash;
    }
    return '${hash.substring(0, 8)}...${hash.substring(hash.length - 6)}';
  }

  static pw.Widget _emptyMessage(String message) {
    return pw.Text(
      message,
      style: pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
    );
  }
}
